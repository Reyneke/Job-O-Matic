/// Status of an application during its lifecycle.
enum ApplicationStatus {
  queued,
  processing,
  completed,
  failed,
  exported;

  String get displayName {
    switch (this) {
      case ApplicationStatus.queued:
        return 'Wartend';
      case ApplicationStatus.processing:
        return 'In Bearbeitung';
      case ApplicationStatus.completed:
        return 'Abgeschlossen';
      case ApplicationStatus.failed:
        return 'Fehlgeschlagen';
      case ApplicationStatus.exported:
        return 'Exportiert';
    }
  }
}

/// E-Mail-Versand-Status einer Bewerbung (unabhängiger Lebenszyklus vom
/// Generierungs-Status) – siehe doc/plan/14-Email.md (Entscheidungen).
///
/// Persistierte Werte: 'new' | 'queued' | 'sending' | 'sent' | 'failed'.
/// `ready` / `needs_address` sind KEINE EmailStatus-Werte, sondern abgeleitete
/// UI-Zustände (aus ApplicationStatus + vorhandener E-Mail-Adresse).
enum EmailStatus {
  /// Neu erstellt – noch kein Versand initiiert.
  initial('new'),
  queued('queued'),
  sending('sending'),
  sent('sent'),
  failed('failed');

  /// In DB und JSON persistierter Wert.
  final String storeValue;

  const EmailStatus(this.storeValue);

  /// Parst einen persistierten Wert zurück; unbekannte Werte fallen auf [initial].
  static EmailStatus fromStoreValue(String value) => values.firstWhere(
    (e) => e.storeValue == value,
    orElse: () => EmailStatus.initial,
  );
}

/// Represents a single job application generated by the system.
class Application {
  final int id;
  final String jobTitle;
  final String company;
  final String? companyAddress;
  final String jobUrl;
  final String? jobDescription;
  final ApplicationStatus status;
  final String? pdfPath;
  final String? errorMessage;
  final DateTime createdAt;
  final DateTime? completedAt;

  /// KI-generierter (oder manuell bearbeiteter) Anschreiben-Text.
  ///
  /// Wird einmal pro Bewerbung generiert und persistiert, damit PDF und
  /// Vorschau auf identischem Text basieren (kein Regenerieren pro Aufruf).
  final String? coverLetterText;

  /// E-Mail-Versand-Status (eigener Lebenszyklus, siehe [EmailStatus]).
  final EmailStatus emailStatus;

  /// Vom Nutzer bestätigte E-Mail-Adresse des Arbeitgebers (Stufe 4 der
  /// Adress-Kaskade bzw. Ergebnis von Stufe 1–3), persistiert.
  final String? emailAddress;

  /// Quelle der ermittelten E-Mail-Adresse (doc/plan/17, DB v8).
  ///
  /// Enthält den String-Wert einer der bestehenden Quell-Enums
  /// (`EmailDiscoverySource` = storedData/mailtoLink/contactPage/none bzw.
  /// `BaContactSource` = description/externalJobPage/employerWebsite/none)
  /// oder `manual` für Stufe 4 (manuelle Eingabe). Bewusst als freier
  /// `String` ohne CHECK-Constraint, damit zukünftige Quellen nicht sofort
  /// eine DB-Migration erzwingen.
  final String? emailSource;

  /// Fundstelle/Beleg-URL, über die die Adresse ermittelt wurde (z. B. die
  /// aufgelöste Kontakt- oder Impressum-Seite) – für Transparenz/Audit.
  final String? emailEvidenceUrl;

  /// Name des Ansprechpartners (optional; z. B. aus der Beschreibung
  /// extrahiert oder manuell ergänzt). Persistiert für UI + PDF-Templates.
  final String? contactPerson;

  const Application({
    required this.id,
    required this.jobTitle,
    required this.company,
    required this.jobUrl,
    this.companyAddress,
    this.jobDescription,
    this.status = ApplicationStatus.queued,
    this.pdfPath,
    this.errorMessage,
    required this.createdAt,
    this.completedAt,
    this.coverLetterText,
    this.emailStatus = EmailStatus.initial,
    this.emailAddress,
    this.emailSource,
    this.emailEvidenceUrl,
    this.contactPerson,
  });

  Application copyWith({
    int? id,
    String? jobTitle,
    String? company,
    String? companyAddress,
    String? jobUrl,
    String? jobDescription,
    ApplicationStatus? status,
    String? pdfPath,
    String? errorMessage,
    DateTime? createdAt,
    DateTime? completedAt,
    String? coverLetterText,
    EmailStatus? emailStatus,
    String? emailAddress,
    String? emailSource,
    String? emailEvidenceUrl,
    String? contactPerson,
  }) {
    return Application(
      id: id ?? this.id,
      jobTitle: jobTitle ?? this.jobTitle,
      company: company ?? this.company,
      companyAddress: companyAddress ?? this.companyAddress,
      jobUrl: jobUrl ?? this.jobUrl,
      jobDescription: jobDescription ?? this.jobDescription,
      status: status ?? this.status,
      pdfPath: pdfPath ?? this.pdfPath,
      errorMessage: errorMessage ?? this.errorMessage,
      createdAt: createdAt ?? this.createdAt,
      completedAt: completedAt ?? this.completedAt,
      coverLetterText: coverLetterText ?? this.coverLetterText,
      emailStatus: emailStatus ?? this.emailStatus,
      emailAddress: emailAddress ?? this.emailAddress,
      emailSource: emailSource ?? this.emailSource,
      emailEvidenceUrl: emailEvidenceUrl ?? this.emailEvidenceUrl,
      contactPerson: contactPerson ?? this.contactPerson,
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'jobTitle': jobTitle,
    'company': company,
    'companyAddress': companyAddress,
    'jobUrl': jobUrl,
    'jobDescription': jobDescription,
    'status': status.name,
    'pdfPath': pdfPath,
    'errorMessage': errorMessage,
    'createdAt': createdAt.toIso8601String(),
    'completedAt': completedAt?.toIso8601String(),
    'coverLetterText': coverLetterText,
    'emailStatus': emailStatus.storeValue,
    'emailAddress': emailAddress,
    'emailSource': emailSource,
    'emailEvidenceUrl': emailEvidenceUrl,
    'contactPerson': contactPerson,
  };

  factory Application.fromJson(Map<String, dynamic> json) => Application(
    id: json['id'] as int,
    jobTitle: json['jobTitle'] as String,
    company: json['company'] as String,
    companyAddress: json['companyAddress'] as String?,
    jobUrl: json['jobUrl'] as String,
    jobDescription: json['jobDescription'] as String?,
    status: ApplicationStatus.values.firstWhere(
      (e) => e.name == json['status'],
      orElse: () => ApplicationStatus.queued,
    ),
    pdfPath: json['pdfPath'] as String?,
    errorMessage: json['errorMessage'] as String?,
    createdAt: DateTime.parse(json['createdAt'] as String),
    completedAt: json['completedAt'] != null
        ? DateTime.parse(json['completedAt'] as String)
        : null,
    coverLetterText: json['coverLetterText'] as String?,
    emailStatus: EmailStatus.fromStoreValue(
      json['emailStatus'] as String? ?? EmailStatus.initial.storeValue,
    ),
    emailAddress: json['emailAddress'] as String?,
    emailSource: json['emailSource'] as String?,
    emailEvidenceUrl: json['emailEvidenceUrl'] as String?,
    contactPerson: json['contactPerson'] as String?,
  );
}
